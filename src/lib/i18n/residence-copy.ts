export function localizeResidence(residence: ResidenceDetails, locale: Locale): ResidenceDetails {
  if (locale === "en") {
    return residence;
  }
  const copy = EL[residence.id];
  return {
    ...residence,
    ...copy,
    sleepingArrangements: copy.sleepingArrangements.map((item, index) => ({
      ...item,
      image: residence.sleepingArrangements[index]?.image,
    })),
  };
}
